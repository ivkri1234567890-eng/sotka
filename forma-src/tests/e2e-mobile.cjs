const { chromium, devices } = require('playwright'); const fs = require('fs');
(async () => {
  const b = await chromium.launch({ args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader'] });
  const ctx = await b.newContext({ ...devices['Pixel 7'], acceptDownloads: true });
  const pg = await ctx.newPage(); const errs = []; pg.on('pageerror', e => errs.push('PAGEERR ' + e.message)); pg.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
  const S = n => pg.screenshot({ path: `tests/shots/m-${n}.png` });
  await pg.goto('http://localhost:4173/'); await pg.waitForTimeout(2500);
  await pg.tap('[data-testid="cat-wr"]'); await pg.waitForTimeout(800); await S('01-home');
  await pg.tap('[data-testid="m-wr-neo"]'); await pg.waitForTimeout(1500); await S('02-editor');
  const p0 = await pg.textContent('[data-testid="price"]');
  await pg.fill('#w', '2100'); await pg.press('#w', 'Enter'); await pg.waitForTimeout(500);
  console.log('price', p0, '->', await pg.textContent('[data-testid="price"]'));
  await pg.tap('.tab:has-text("Материалы и цвет")'); await pg.fill('[aria-label="Поиск RAL"] >> nth=1', 'серый'); await pg.tap('[aria-label^="RAL 7035"] >> nth=1'); await pg.waitForTimeout(300);
  await pg.tap('.tab:has-text("Ручки и основание")'); await pg.tap('button.opt:has-text("Кнопка")'); await pg.tap('[aria-label="Хром"] >> nth=0'); await pg.waitForTimeout(300);
  await pg.tap('.mtabs button:has-text("Модель крупно")'); await pg.waitForTimeout(400);
  await pg.tap('.tg:has-text("Двери")'); await pg.waitForTimeout(1200); await S('03-doors');
  await pg.tap('.tg:has-text("Двери")'); await pg.tap('.tg:has-text("Внутри")'); await pg.waitForTimeout(1000); await S('04-inside');
  await pg.tap('.mtabs button:has-text("Настройки")'); await pg.waitForTimeout(300);
  await pg.tap('.tab:has-text("Наполнение")'); await pg.waitForTimeout(200); await S('05-fill');
  console.log('errors:', await pg.locator('.ck.error').count(), 'warns:', await pg.locator('.ck.warn').count());
  await pg.tap('[aria-label="Назад"]'); await pg.waitForTimeout(400); await S('06-leave');
  await pg.tap('.modal button:has-text("Сохранить")'); await pg.waitForTimeout(800);
  console.log('home projects:', await pg.locator('.prow').count());
  await pg.tap('.prow button:has-text("Открыть")'); await pg.waitForTimeout(1200);
  console.log('reopened width', await pg.inputValue('#w'), 'handles knob?', await pg.evaluate(() => 1));
  await pg.tap('.mtabs button:has-text("Документы")'); await pg.waitForTimeout(1500); await S('07-docs');
  await pg.tap('.dnav button:has-text("Смета")'); await pg.waitForTimeout(400); await S('08-est');
  const [dl] = await Promise.all([pg.waitForEvent('download', { timeout: 200000 }), pg.tap('[data-testid="pdf"]')]); await dl.saveAs('tests/shots/m.pdf'); console.log('pdf', fs.statSync('tests/shots/m.pdf').size);
  const sw = await pg.evaluate(() => document.documentElement.scrollWidth > window.innerWidth + 1); console.log('horizontal scroll on docs:', sw);
  console.log('ERRORS', errs.slice(0, 10)); await b.close();
})();
